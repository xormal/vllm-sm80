"""[ОДИН ГРАФ 30.10] ПОЛНЫЙ CUDA-ГРАФ СМЕШАННОГО ШАГА С CLEF (FA2SM70_FULL_MIX=1).

Смешанный шаг под нагрузкой Clef -- это D строк спекулятивного декода чатов (по k+1 токенов, идут ПЕРВЫМИ в батче) и
1-3 куска префилла (запись Clef, иногда префилл чата). Он шёл eager (force_eager) или кусочным графом has_clef. Здесь --
ОДИН полный граф на весь проход цели, ключ -- только T (дополненное число токенов, корзины FA2SM70_FULL_MIX_SIZES):
граф НЕ зависит от состава шага. Окно 18: с ключом (T, D) каждый граф держал ~36 МиБ драйвера (~10 тыс. узлов) и 81
граф не помещался; без D -- по графу на корзину. Строки батча дополнены до R = max_num_seqs (нулевой длины, таблица
блоков -1); спекулятивные строки -- до Dmax (строки D..Dmax-1 нулевой длины, индексы состояний PAD); всё, что зависит
от длин, лежит в постоянных буферах и заполняется на хосте перед повтором (построители метаданных):
  * внимание: однородное ядро декода на Dmax строк (длины строк-не-спекуляций -- 0, маска -- черновики на карте), затем
    varlen-ядро по ВСЕМ R строкам (у спекулятивных sq=0), метаданные varlen граф строит сам из постоянных qsl/seq_lens;
  * GDN: обновление свёртки и рекуррент спекуляции на Dmax строк (нулевые и PAD ядра пропускают), conv1d_fn и ОДИН
    varlen-скан по всем R строкам в абсолютных координатах токенов (у спекулятивных длина 0); выход скана -- по маске
    токенов; запись состояния заполнителей -- в нулевой блок пула;
  * планировщик не режет кусок через границу блока mamba (FA2SM70_FULL_MIX: кусок кончается на границе), поэтому
    varlen-скан годен всегда;
  * поправка Clef -- delta_graph (строки по списку/маске на карте), обмен TP -- копировщиком в графе.
Шаг, не подходящий под раскладку (спекулятивная строка не k+1 токенов, спекулятивные не первыми, пересечение
границы блока, нет графа под (T, D)) -- прежним путём (кусочный граф has_clef или eager).
"""
import os

ВКЛ = os.environ.get("FA2SM70_FULL_MIX", "0") == "1"
_РАЗМЕРЫ = tuple(sorted(int(x) for x in os.environ.get(
    "FA2SM70_FULL_MIX_SIZES", "256,512,768,1024,1280,1536,1792,2040").split(",") if x.strip()))
DMAX = int(os.environ.get("FA2SM70_FULL_MIX_DMAX", "8"))
# Переключатель-файл для A/B в одном экземпляре (графы захвачены всегда, берутся только при "2"). Значения совместимы с
# FA2SM70_CLEF_GRAPH_FILE на том же файле: "0" -- шаг с Clef eager, "1" -- кусочный граф has_clef, "2" -- полный граф.
_ФАЙЛ = os.environ.get("FA2SM70_FULL_MIX_FILE", "")

# [ФРИЗЫ 30.10] СОГЛАСОВАННЫЙ МЕЖДУ РАНГАМИ TP ПЕРЕКЛЮЧАТЕЛЬ-ФАЙЛ. Раньше каждый ранг перечитывал файл раз в секунду
# сам: при переключении под нагрузкой один ранг брал граф (обмен копировщиком в графе: свой приёмник, флаги, номер на
# устройстве), другой -- eager (свой протокол) -> ожидание до срыва и неверные данные. Теперь значение меняется ТОЛЬКО на
# шаге планировщика с номером, кратным _ПЕРИОД: ранг 0 читает файлы и рассылает по CPU-группе TP (gloo), все ранги
# переключаются на одном и том же шаге. Набор файлов -- из окружения при импорте (одинаков на рангах), поэтому решение
# «рассылать или нет» тоже одинаково и тупика нет. До первого шага ранги читают файл сами (при старте его не меняют).
_ПЕРИОД = int(os.environ.get("FA2SM70_MODE_FILE_PERIOD", "64"))
_ФАЙЛЫ = {}                  # путь -> согласованный первый байт
for _п in {_ФАЙЛ, os.environ.get("FA2SM70_CLEF_GRAPH_FILE", "")}:
    if _п:
        _ФАЙЛЫ[_п] = None
_ШАГ = {"n": 0}


def _прочитать(путь):
    """Первый байт файла; "" -- файл пуст; "-" -- файла нет (раньше: нет файла -- включено, пустой -- выключено)."""
    try:
        with open(путь) as f:
            return f.read(1)
    except OSError:
        return "-"


def значение_файла(путь):
    """Согласованное между рангами TP значение файла-переключателя (первый байт; "" -- пуст, "-" -- файла нет)."""
    if путь not in _ФАЙЛЫ:
        return _прочитать(путь)          # не из согласуемого набора -- как раньше
    if _ФАЙЛЫ[путь] is None:
        _ФАЙЛЫ[путь] = _прочитать(путь)
    return _ФАЙЛЫ[путь]


def шаг_режима():
    """Раз на шаг планировщика на ВСЕХ рангах TP (начало execute_model)."""
    if not _ФАЙЛЫ:
        return
    _ШАГ["n"] += 1
    if _ШАГ["n"] % _ПЕРИОД and _ШАГ["n"] != 1:     # [ревизия] и на первом шаге: до него ранги читали файл сами
        return
    import torch.distributed as dist
    from vllm.distributed.parallel_state import get_tp_group
    g = get_tp_group()
    знач = [{п: _прочитать(п) for п in sorted(_ФАЙЛЫ)} if g.rank_in_group == 0 else None]
    if g.world_size > 1:
        dist.broadcast_object_list(знач, src=g.ranks[0], group=g.cpu_group)
    _ФАЙЛЫ.update(знач[0])

# Постоянный тензор черновиков на строку (раннер: num_decode_draft_tokens.gpu; >= 0 -- строка спекуляции) и k+1 --
# ставит раннер; внимание в графе строит по ним маску спекулятивных строк.
ЧЕРНОВИКИ = [None]
K1 = [1]
# Шаг полного графа, который сейчас строится/исполняется: (T, D, Dmax) или None. Ставит раннер вокруг построения
# метаданных и прохода (и в фиктивных проходах захвата); читают построители метаданных и слои.
ШАГ = [None]
С = {"шагов": 0, "отказ_раскладка": 0, "отказ_граница": 0, "отказ_размер": 0}


def вкл_сейчас():
    if not ВКЛ:
        return False
    if _ФАЙЛ:
        v = значение_файла(_ФАЙЛ)
        return v == "2" or v == "-"        # нет файла -- включено, пустой -- выключено (как раньше)
    return True


def размеры():
    return _РАЗМЕРЫ


def dmax_для(T, k1, R):
    """Сколько спекулятивных строк вмещает граф корзины T (все -- по k+1 токенов, хотя бы один токен префилла)."""
    return max(0, min(DMAX, R - 1, (T - 1) // max(k1, 1)))


def ключи(k1, R):
    """Корзины (T, Dmax), под которые захватываются графы -- по одному на T."""
    return [(T, dmax_для(T, k1, R)) for T in _РАЗМЕРЫ]


def план(num_tokens, num_reqs, nst, ndraft, ncomp, k, R, B_mamba, есть):
    """Подходит ли шаг под полный граф: (T, D) или None. Всё по ХОСТОВЫМ массивам шага (без обращений к карте).
    nst -- токенов на строку, ndraft -- черновых токенов на строку декода (-1 у префилла), ncomp -- посчитано до шага,
    k -- число черновых, R -- потолок строк, B_mamba -- размер блока состояния, есть(T, D) -- граф захвачен."""
    k1 = k + 1
    D = 0
    while D < num_reqs and ndraft[D] >= 0:
        D += 1
    if D > DMAX or num_reqs > R or D >= R:
        С["отказ_раскладка"] += 1
        return None
    for i in range(D):
        if int(nst[i]) != k1 or int(ndraft[i]) != k:
            С["отказ_раскладка"] += 1
            return None
    for i in range(D, num_reqs):
        if ndraft[i] >= 0:                          # спекулятивная строка ПОСЛЕ префилла -- раскладка не статична
            С["отказ_раскладка"] += 1
            return None
        if B_mamba > 0:
            C, n = int(ncomp[i]), int(nst[i])
            if (C // B_mamba + 1) * B_mamba < C + n:
                С["отказ_граница"] += 1
                return None
    for T in _РАЗМЕРЫ:
        if T >= num_tokens and есть(T, D):
            С["шагов"] += 1
            return (T, D)
    С["отказ_размер"] += 1
    return None
